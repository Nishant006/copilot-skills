  echo "  copilot-skills graphify      Knowledge graph management"
  echo "  copilot-skills --help        Show all options"
  echo ""
  echo "  💡 Just type 'copilot-skills' in any project. It figures out the rest."
  echo ""
  echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

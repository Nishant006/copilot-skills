# ─── Install into a shell RC file ─────────────────────────────────────────────
install_to_rc() {
  local rc_file="$1"
  local shell_name="$2"

  if [ ! -f "$rc_file" ]; then
    touch "$rc_file"
  fi

  # Remove existing block (idempotent)
  if grep -q "$MARKER_START" "$rc_file" 2>/dev/null; then
    # Use sed to remove between markers (inclusive)
    local tmp_file="${rc_file}.copilot-skills-tmp"
    sed "/$MARKER_START/,/$MARKER_END/d" "$rc_file" > "$tmp_file"
    mv "$tmp_file" "$rc_file"
    echo "  ♻️  Replaced existing copilot-skills block in $rc_file"
  else
    echo "  ✨ Adding copilot-skills block to $rc_file"
  fi

  # Append new block
  echo "" >> "$rc_file"
  generate_shell_block >> "$rc_file"
  echo "  ✅ $shell_name configured"
}

# ─── Uninstall ────────────────────────────────────────────────────────────────
uninstall() {
  echo "🗑️  Uninstalling copilot-skills shell functions..."
  echo ""

  local removed=0
  for rc_file in "$HOME/.zshrc" "$HOME/.bashrc"; do
    if [ -f "$rc_file" ] && grep -q "$MARKER_START" "$rc_file" 2>/dev/null; then
      local tmp_file="${rc_file}.copilot-skills-tmp"
      sed "/$MARKER_START/,/$MARKER_END/d" "$rc_file" > "$tmp_file"
      mv "$tmp_file" "$rc_file"
      echo "  ✅ Removed from $rc_file"
      removed=$((removed + 1))
    fi
  done

  if [ "$removed" -eq 0 ]; then
    echo "  ℹ️  No copilot-skills block found in ~/.zshrc or ~/.bashrc"
  else
    echo ""
    echo "Done! Restart your shell or run: exec \$SHELL"
  fi
}

# ─── Main ─────────────────────────────────────────────────────────────────────

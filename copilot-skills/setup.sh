  else
    echo "  ✅ node $(node --version)"
  fi

  if [ "$prereq_warnings" -gt 0 ]; then
    echo ""
    echo "  ⚠️  $prereq_warnings optional tools missing — some skills may be limited."
    echo "     Setup will continue. Install missing tools when needed."
  fi
  echo ""


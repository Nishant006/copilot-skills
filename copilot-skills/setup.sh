#!/usr/bin/env bash
# ╔══════════════════════════════════════════════════════════════════════════════╗
# ║  Copilot Skills — One-Command Setup                                         ║
# ║  Run: ./setup.sh                                                            ║
# ║  Uninstall: ./setup.sh --uninstall                                          ║
# ╚══════════════════════════════════════════════════════════════════════════════╝
#
# What this does:
#   1. Detects where .copilot-skills/ lives (no hardcoded paths)
#   2. Adds shell functions to ~/.zshrc and/or ~/.bashrc
#   3. Makes `copilot-link-skills` available immediately
#
# Idempotent: safe to re-run. Replaces old block if already present.

set -euo pipefail

# ─── Resolve this script's real directory ─────────────────────────────────────
SCRIPT_PATH="${BASH_SOURCE[0]:-$0}"
while [ -L "$SCRIPT_PATH" ]; do
  DIR="$(cd -P "$(dirname "$SCRIPT_PATH")" && pwd)"
  SCRIPT_PATH="$(readlink "$SCRIPT_PATH")"
  [[ "$SCRIPT_PATH" != /* ]] && SCRIPT_PATH="$DIR/$SCRIPT_PATH"
done
SKILLS_ROOT="$(cd -P "$(dirname "$SCRIPT_PATH")" && pwd)"

# ─── Config ──────────────────────────────────────────────────────────────────
MARKER_START="# >>> copilot-skills >>>"
MARKER_END="# <<< copilot-skills <<<"
# Shell block version tracks the main VERSION file to prevent drift
SHELL_BLOCK_VERSION="$(cat "$SKILLS_ROOT/VERSION" 2>/dev/null | tr -d '[:space:]')"

# ─── Generate shell block ─────────────────────────────────────────────────────
generate_shell_block() {
  cat <<BLOCK
$MARKER_START
# Copilot Skills v${SHELL_BLOCK_VERSION} — auto-generated by setup.sh
# Source: $SKILLS_ROOT
export COPILOT_SKILLS_ROOT="$SKILLS_ROOT"

# Link skills into current project, or --all for all sibling projects
copilot-link-skills() {
  if [ "\${1:-}" = "--help" ] || [ "\${1:-}" = "-h" ]; then
    echo "Usage: copilot-link-skills [project-name | --all | -a]"
    echo ""
    echo "Link AI workflow skills into the current git project via symlinks."
    echo ""
    echo "Options:"
    echo "  (no args)      Auto-detect project name from git remote, link skills"
    echo "  <project-name> Use specific project overlay (e.g., 'communication-dispatcher')"
    echo "  --all, -a      Link skills into ALL sibling projects"
    echo "  --help, -h     Show this help"
    return 0
  fi
  source "\$COPILOT_SKILLS_ROOT/link-skills.sh"
  if [ "\${1:-}" = "--all" ] || [ "\${1:-}" = "-a" ]; then
    link_all
  else
    link_skills "\$@"
  fi
}

# Check skills status in current project
copilot-check-skills() {
  if [ "\${1:-}" = "--help" ] || [ "\${1:-}" = "-h" ]; then
    echo "Usage: copilot-check-skills [project-name]"
    echo ""
    echo "Check if linked skills are up-to-date in the current project."
    echo "Reports: missing skills, stale versions, graphify freshness."
    echo ""
    echo "Options:"
    echo "  (no args)      Auto-detect project name"
    echo "  <project-name> Check specific project overlay"
    echo "  --help, -h     Show this help"
    return 0
  fi
  source "\$COPILOT_SKILLS_ROOT/link-skills.sh"
  check_skills "\$@"
}

# Update skills (re-link + check)
copilot-update-skills() {
  if [ "\${1:-}" = "--help" ] || [ "\${1:-}" = "-h" ]; then
    echo "Usage: copilot-update-skills [project-name | --all | -a]"
    echo ""
    echo "Re-link all skills + verify they are current. Equivalent to:"
    echo "  copilot-link-skills && copilot-check-skills"
    echo ""
    echo "Options:"
    echo "  (no args)      Auto-detect project name"
    echo "  <project-name> Update specific project overlay"
    echo "  --all, -a      Update ALL sibling projects"
    echo "  --help, -h     Show this help"
    return 0
  fi
  source "\$COPILOT_SKILLS_ROOT/link-skills.sh"
  if [ "\${1:-}" = "--all" ] || [ "\${1:-}" = "-a" ]; then
    update_all
  else
    update_skills "\$@"
  fi
}

# ─── THE ONE COMMAND ─────────────────────────────────────────────────────────
# copilot-skills: single entry point for everything. Idempotent. Context-aware.
copilot-skills() {
  local cmd="\${1:-}"
  
  if [ "\$cmd" = "--help" ] || [ "\$cmd" = "-h" ]; then
    echo "Usage: copilot-skills [command]"
    echo ""
    echo "Daily"
    echo "  (no args)     Health dashboard — check + offer fixes (context-aware)"
    echo "  check         Health report for current project (or --all)"
    echo "  link          Re-link skills into current project (or --all)"
    echo "  sync          Pull latest source + re-link all projects"
    echo ""
    echo "Maintenance"
    echo "  update        Re-link + verify current project (or --all)"
    echo "  setup         Full re-install (shell block + prereqs + link all)"
    echo "  edit [name]   Open skills source for editing"
    echo "  new <name>    Create a new project overlay"
    echo "  graphify      Knowledge graph management"
    echo ""
    echo "Flags"
    echo "  --all, -a     Apply to all sibling projects"
    echo ""
    echo "Examples"
    echo "  copilot-skills              # Dashboard: shows all projects health"
    echo "  copilot-skills sync         # Pull latest + re-link everything"
    echo "  copilot-skills link --all   # Re-link all projects"
    return 0
  fi

  source "\$COPILOT_SKILLS_ROOT/link-skills.sh"

  case "\$cmd" in
    sync)
      copilot-sync-skills
      ;;
    check)
      shift 2>/dev/null
      if [ "\${1:-}" = "--all" ] || [ "\${1:-}" = "-a" ]; then
        _copilot_check_all
      else
        check_skills "\$@"
      fi
      ;;
    link)
      shift 2>/dev/null
      if [ "\${1:-}" = "--all" ] || [ "\${1:-}" = "-a" ]; then
        link_all
      else
        link_skills "\$@"
      fi
      ;;
    update)
      shift 2>/dev/null
      if [ "\${1:-}" = "--all" ] || [ "\${1:-}" = "-a" ]; then
        update_all
      else
        update_skills "\$@"
      fi
      ;;
    setup)
      echo "🔄 Running full setup..."
      (cd "\$COPILOT_SKILLS_ROOT" && ./setup.sh)
      ;;
    edit)
      shift 2>/dev/null
      copilot-edit-skills "\$@"
      ;;
    new)
      shift 2>/dev/null
      copilot-new-project "\$@"
      ;;
    graphify)
      shift 2>/dev/null
      copilot-graphify "\$@"
      ;;
    --all|-a)
      _copilot_smart_all
      ;;
    "")
      _copilot_smart_mode
      ;;
    *)
      echo "❌ Unknown command: \$cmd"
      echo "Run 'copilot-skills --help' for usage."
      return 1
      ;;
  esac
}

# Smart mode: auto-detects context and does the right thing
_copilot_smart_mode() {
  source "\$COPILOT_SKILLS_ROOT/link-skills.sh"
  # If inside the skills repo itself, treat as "not in a project"
  if [ "\$(cd "\$PWD" && pwd)" = "\$(cd "\$COPILOT_SKILLS_ROOT" && pwd)" ]; then
    _copilot_smart_all
    return
  fi
  # Check if we're inside a git repo (supports subdirs and worktrees)
  local repo_root=""
  repo_root=\$(git rev-parse --show-toplevel 2>/dev/null)
  if [ -n "\$repo_root" ]; then
    # cd to repo root for consistent behavior
    local orig_dir="\$PWD"
    cd "\$repo_root" || { _copilot_smart_all; return; }
    echo "📍 Project: \$(basename "\$PWD")"
    [ "\$orig_dir" != "\$PWD" ] && echo "   (detected from subdirectory)"
    echo ""
    if [ -f "AGENTS.md" ]; then
      # Already linked — check freshness (use exit code, not grep)
      local result
      local check_exit=0
      result=\$(check_skills 2>&1) || check_exit=\$?
      if [ "\$check_exit" -ne 0 ]; then
        # Auto-fix: re-link silently (project is already linked, just stale)
        link_skills >/dev/null 2>&1
        echo "  ↻ Symlinks refreshed"
        # Re-check after fix
        result=\$(check_skills 2>&1) || true
        echo "\$result"
      else
        echo "\$result"
      fi
    else
      # Not linked yet — offer to link
      echo "⚠️  Skills not linked in this project."
      echo -n "🔗 Link now? [Y/n] "
      read -r link_answer </dev/tty 2>/dev/null || link_answer="Y"
      if [ "\${link_answer:-Y}" != "n" ] && [ "\${link_answer:-Y}" != "N" ]; then
        link_skills
      fi
    fi
    cd "\$orig_dir" 2>/dev/null
  else
    # Not in a project — check all
    _copilot_smart_all
  fi
}

# Smart --all: health dashboard for all projects
_copilot_smart_all() {
  source "\$COPILOT_SKILLS_ROOT/link-skills.sh"
  local parent_dir="\$(cd "\$COPILOT_SKILLS_ROOT/.." && pwd)"
  local source_version="?"
  [ -f "\$COPILOT_SKILLS_ROOT/VERSION" ] && source_version=\$(cat "\$COPILOT_SKILLS_ROOT/VERSION" | tr -d '[:space:]')
  local generic_count=\$(ls -d "\$COPILOT_SKILLS_ROOT/generic/.github/skills"/*/ 2>/dev/null | wc -l | tr -d ' ')
  
  # Pre-check: auto-fix stale symlinks BEFORE displaying the table
  local has_unlinked=0
  local any_stale=0
  for dir in "\$parent_dir"/*/; do
    _is_git_repo "\$dir" || continue
    local dirname="\$(basename "\$dir")"
    [ "\$dirname" = ".copilot-skills" ] && continue
    [[ "\$dirname" == .* ]] && continue
    if [ ! -f "\$dir/AGENTS.md" ]; then
      has_unlinked=1
    elif ! (cd "\$dir" && check_skills >/dev/null 2>&1); then
      any_stale=1
    fi
  done
  
  # Auto-fix linked-but-stale projects silently before showing dashboard
  if [ "\$any_stale" -eq 1 ] && [ "\$has_unlinked" -eq 0 ]; then
    link_all >/dev/null 2>&1
  fi
  
  # Now display the dashboard (should be clean after auto-fix)
  echo "┌─────────────────────────────────────────────┐"
  echo "│  copilot-skills — project health dashboard  │"
  echo "└─────────────────────────────────────────────┘"
  echo ""
  echo "  Source: v\$source_version · \$generic_count generic skills"
  echo ""
  echo "  ──────────────────────────────────────────────────────────────────────"
  printf "  %-3s %-30s %6s  %-9s %-16s  %s\n" "" "Project" "Skills" "Version" "Linked" "Graph"
  echo "  ──────────────────────────────────────────────────────────────────────"
  
  local needs_fix=0
  local total_projects=0
  local fix_list=""
  
  for dir in "\$parent_dir"/*/; do
    _is_git_repo "\$dir" || continue
    local dirname="\$(basename "\$dir")"
    [ "\$dirname" = ".copilot-skills" ] && continue
    [[ "\$dirname" == .* ]] && continue
    total_projects=\$((total_projects + 1))
    
    if [ -f "\$dir/AGENTS.md" ]; then
      local linked_v="?"
      local stamp_file="\$dir/.github/.copilot-skills-version"
      [ -f "\$stamp_file" ] && linked_v=\$(cat "\$stamp_file" | tr -d '[:space:]')
      local skill_count=\$(ls -d "\$dir/.github/skills"/*/ 2>/dev/null | wc -l | tr -d ' ')
      local linked_date=\$(stat -f "%Sm" -t "%Y-%m-%d %H:%M" "\$stamp_file" 2>/dev/null || date -r "\$stamp_file" "+%Y-%m-%d %H:%M" 2>/dev/null || stat -c "%y" "\$stamp_file" 2>/dev/null | cut -d. -f1 || echo "unknown")
      local graph_status="—"
      if [ -f "\$dir/graphify-out/graph.json" ] || { [ -L "\$dir/graphify-out" ] && [ -f "\$dir/graphify-out/graph.json" ]; }; then
        local stale_graph=\$(find "\$dir/graphify-out/graph.json" -mtime +7 -print 2>/dev/null)
        if [ -n "\$stale_graph" ]; then
          graph_status="stale"
        else
          graph_status="✓"
        fi
      fi
      
      # Use exit code to determine health
      local check_exit=0
      (cd "\$dir" && check_skills >/dev/null 2>&1) || check_exit=\$?
      if [ "\$check_exit" -ne 0 ]; then
        local version_str="v\$linked_v"
        [ "\$linked_v" != "\$source_version" ] && version_str="v\$linked_v→v\$source_version"
        printf "  ⚠️  %-30s %4s   %-9s %-16s  %s\n" "\$dirname" "\$skill_count" "\$version_str" "\$linked_date" "\$graph_status"
        needs_fix=\$((needs_fix + 1))
        fix_list="\$fix_list \$dirname"
      else
        printf "  ✅  %-30s %4s   v%-8s %-16s  %s\n" "\$dirname" "\$skill_count" "\$linked_v" "\$linked_date" "\$graph_status"
      fi
    else
      printf "  ⚠️  %-30s %4s   %-9s %-16s  %s\n" "\$dirname" "—" "unlinked" "—" "—"
      needs_fix=\$((needs_fix + 1))
      fix_list="\$fix_list \$dirname"
    fi
  done
  
  echo "  ──────────────────────────────────────────────────────────────────────"
  echo ""
  if [ "\$needs_fix" -gt 0 ]; then
    echo "  \$needs_fix/\$total_projects projects need action:\$fix_list"
    echo ""
    echo -n "  Run 'copilot-skills link --all' now? (re-links local symlinks only) [Y/n] "
    read -r fix_answer </dev/tty 2>/dev/null || fix_answer="Y"
    if [ "\${fix_answer:-Y}" != "n" ] && [ "\${fix_answer:-Y}" != "N" ]; then
      link_all
    fi
  else
    echo "  ✅ All \$total_projects projects healthy!"
  fi
}

# Check all projects (non-interactive report)
_copilot_check_all() {
  source "\$COPILOT_SKILLS_ROOT/link-skills.sh"
  local parent_dir="\$(cd "\$COPILOT_SKILLS_ROOT/.." && pwd)"
  for dir in "\$parent_dir"/*/; do
    _is_git_repo "\$dir" || continue
    local dirname="\$(basename "\$dir")"
    [ "\$dirname" = ".copilot-skills" ] && continue
    [[ "\$dirname" == .* ]] && continue
    echo "━━━ \$dirname ━━━"
    (cd "\$dir" && check_skills 2>&1) | sed 's/^/  /'
    echo ""
  done
}

# Sync: pull latest from remote + re-link all projects
copilot-sync-skills() {
  echo "🔄 Syncing copilot-skills from remote..."
  local old_version="?"
  [ -f "\$COPILOT_SKILLS_ROOT/VERSION" ] && old_version=\$(cat "\$COPILOT_SKILLS_ROOT/VERSION" | tr -d '[:space:]')
  local old_sha=\$(cd "\$COPILOT_SKILLS_ROOT" && git rev-parse --short HEAD 2>/dev/null)
  
  (cd "\$COPILOT_SKILLS_ROOT" && git pull --ff-only 2>&1) || {
    echo "❌ Git pull failed. Resolve manually: cd \$COPILOT_SKILLS_ROOT && git status"
    return 1
  }
  
  local new_version="?"
  [ -f "\$COPILOT_SKILLS_ROOT/VERSION" ] && new_version=\$(cat "\$COPILOT_SKILLS_ROOT/VERSION" | tr -d '[:space:]')
  local new_sha=\$(cd "\$COPILOT_SKILLS_ROOT" && git rev-parse --short HEAD 2>/dev/null)
  
  echo ""
  if [ "\$old_sha" != "\$new_sha" ]; then
    echo "  Updated: v\$old_version → v\$new_version (\$old_sha → \$new_sha)"
    echo "  Changed:"
    (cd "\$COPILOT_SKILLS_ROOT" && git diff --name-only "\$old_sha..\$new_sha" -- setup.sh link-skills.sh generic projects 2>/dev/null | head -10 | sed 's/^/    - /')
    local total_changed=\$(cd "\$COPILOT_SKILLS_ROOT" && git diff --name-only "\$old_sha..\$new_sha" -- setup.sh link-skills.sh generic projects 2>/dev/null | wc -l | tr -d ' ')
    [ "\$total_changed" -gt 10 ] && echo "    ... and \$((total_changed - 10)) more"
  else
    echo "  Already up to date (v\$new_version)"
  fi
  echo ""
  echo "  Re-linking all projects..."
  source "\$COPILOT_SKILLS_ROOT/link-skills.sh"
  link_all
}

# Graphify — Knowledge graph management
copilot-graphify() {
  local cmd="\${1:-status}"

  # Respect COPILOT_GRAPHIFY_ENABLED
  if [ "\${COPILOT_GRAPHIFY_ENABLED:-1}" = "0" ]; then
    echo "ℹ️  Graphify is disabled (COPILOT_GRAPHIFY_ENABLED=0)"
    echo "   Enable with: export COPILOT_GRAPHIFY_ENABLED=1"
    return 0
  fi

  case "\$cmd" in
    status)
      echo "🧠 Graphify Status"
      echo ""
      if ! command -v graphify &>/dev/null; then
        echo "  ❌ Not installed"
        echo "  Install: uv tool install graphifyy"
        return 1
      fi
      echo "  ✅ Installed: \$(graphify --version 2>/dev/null)"
      echo ""
      if [ -f "graphify-out/graph.json" ]; then
        local mod_date
        mod_date="\$(stat -f '%Sm' -t '%Y-%m-%d %H:%M' graphify-out/graph.json 2>/dev/null || stat -c '%y' graphify-out/graph.json 2>/dev/null | cut -d. -f1)"
        local stale
        stale="\$(find graphify-out/graph.json -mtime +7 -print 2>/dev/null)"
        if [ -n "\$stale" ]; then
          echo "  ⚠️  Graph: graphify-out/graph.json (STALE — last built: \$mod_date)"
          echo "  Refresh with: graphify . --update"
        else
          echo "  ✅ Graph: graphify-out/graph.json (fresh — built: \$mod_date)"
        fi
      elif [ -L "graphify-out" ] && [ -f "graphify-out/graph.json" ]; then
        echo "  ✅ Graph: graphify-out → \$(readlink graphify-out) (symlinked)"
      else
        echo "  ❌ No graph found in current directory"
        echo "  Build with: graphify ."
      fi
      ;;
    rebuild|build|refresh)
      if ! command -v graphify &>/dev/null; then
        echo "❌ Graphify not installed. Install: uv tool install graphifyy"
        return 1
      fi
      echo "🔄 Building knowledge graph for: \$(basename \$PWD)"
      echo "   (AST-only, no API key needed)"
      echo ""
      graphify update .
      graphify hook install 2>/dev/null && echo "   🔗 Git hook installed (auto-updates on commit)" || true
      echo ""
      echo "✅ Graph built. Copilot will now use it for architecture questions."
      ;;
    rebuild-all|all)
      if ! command -v graphify &>/dev/null; then
        echo "❌ Graphify not installed. Install: uv tool install graphifyy"
        return 1
      fi
      local parent_dir="\$(cd "\$COPILOT_SKILLS_ROOT/.." && pwd)"
      echo "🔄 Rebuilding graphs for all projects in: \$parent_dir"
      echo ""
      for dir in "\$parent_dir"/*/; do
        if [ -d "\$dir/.git" ]; then
          echo "  📦 \$(basename "\$dir")..."
          (cd "\$dir" && graphify update . 2>&1 | tail -2) || echo "  ⚠️  Failed"
          (cd "\$dir" && graphify hook install 2>/dev/null) || true
          echo ""
        fi
      done
      echo "✅ All project graphs rebuilt."
      ;;
    query|q)
      shift
      if [ -f "graphify-out/graph.json" ]; then
        graphify query "\$*"
      else
        echo "❌ No graph.json found. Run: graphify ."
      fi
      ;;
    path|p)
      shift
      if [ -f "graphify-out/graph.json" ]; then
        graphify path "\$1" "\$2"
      else
        echo "❌ No graph.json found. Run: graphify ."
      fi
      ;;
    explain|e)
      shift
      if [ -f "graphify-out/graph.json" ]; then
        graphify explain "\$*"
      else
        echo "❌ No graph.json found. Run: graphify ."
      fi
      ;;
    install)
      if command -v graphify &>/dev/null; then
        echo "✅ Already installed: \$(graphify --version 2>/dev/null)"
      else
        if command -v uv &>/dev/null; then
          echo "📦 Installing graphify via uv..."
          uv tool install graphifyy
        elif command -v pipx &>/dev/null; then
          echo "📦 Installing graphify via pipx..."
          pipx install graphifyy
        else
          echo "❌ Need uv or pipx. Install uv: curl -LsSf https://astral.sh/uv/install.sh | sh"
          return 1
        fi
        echo ""
        echo "🔧 Registering with Copilot..."
        graphify install --platform copilot 2>/dev/null || true
        echo "✅ Done. Run: graphify ."
      fi
      ;;
    upgrade)
      if command -v uv &>/dev/null; then
        echo "📦 Upgrading graphify..."
        uv tool upgrade graphifyy
      elif command -v pipx &>/dev/null; then
        pipx upgrade graphifyy
      else
        pip3 install --upgrade graphifyy
      fi
      echo "✅ Upgraded to: \$(graphify --version 2>/dev/null)"
      ;;
    help|--help|-h)
      echo "🧠 copilot-graphify — Knowledge Graph Management"
      echo ""
      echo "Usage: copilot-graphify <command>"
      echo ""
      echo "Commands:"
      echo "  status           Show graphify installation and graph status (default)"
      echo "  rebuild          Build/rebuild graph for current project"
      echo "  rebuild-all      Rebuild graphs for ALL sibling projects"
      echo "  query <question> Query the knowledge graph"
      echo "  path <A> <B>     Find shortest path between two concepts"
      echo "  explain <X>      Explain a concept and its neighbors"
      echo "  install          Install graphify (uv/pipx)"
      echo "  upgrade          Upgrade to latest version"
      echo "  help             Show this help"
      echo ""
      echo "Configuration:"
      echo "  COPILOT_GRAPHIFY_ENABLED=0   Disable graphify integration"
      echo "  COPILOT_GRAPHIFY_PATH=<dir>  Custom graphify-out location"
      ;;
    *)
      echo "❌ Unknown command: \$cmd"
      echo "Run: copilot-graphify help"
      return 1
      ;;
  esac
}

# Open the skills source for editing
copilot-edit-skills() {
  local target="\${1:-}"
  local root="\$COPILOT_SKILLS_ROOT"

  if [ -z "\$target" ]; then
    echo "📂 Skills root: \$root"
    echo ""
    echo "Usage:"
    echo "  copilot-edit-skills generic          # edit shared skills"
    echo "  copilot-edit-skills <project-name>   # edit any project overlay"
    echo ""
    echo "Available projects:"
    ls "\$root/projects/" 2>/dev/null | sed 's/^/  /'
    return 0
  fi

  case "\$target" in
    generic) cd "\$root/generic" && echo "📂 \$(pwd)" ;;
    *)
      if [ -d "\$root/projects/\$target" ]; then
        cd "\$root/projects/\$target" && echo "📂 \$(pwd)"
      else
        echo "❌ No project overlay for '\$target'"
        echo "Create one with: copilot-new-project \$target"
      fi
      ;;
  esac
}

# Add a new project overlay
copilot-new-project() {
  local name="\${1:-}"
  if [ -z "\$name" ]; then
    echo "Usage: copilot-new-project <project-name>"
    return 1
  fi
  local root="\$COPILOT_SKILLS_ROOT/projects/\$name"
  mkdir -p "\$root/.github/skills" "\$root/.github/instructions"

  # Generate copilot-instructions.md from template
  local template="\$COPILOT_SKILLS_ROOT/generic/.github/copilot-instructions.template.md"
  local target="\$root/.github/copilot-instructions.md"
  if [ ! -f "\$target" ] && [ -f "\$template" ]; then
    sed "s/{{PROJECT_NAME}}/\$name/g" "\$template" > "\$target"
    echo "  ✅ copilot-instructions.md (from template — fill in [PROJECT-SPECIFIC] sections)"
  fi

  # Create empty overlay files
  [ -f "\$root/AGENTS-overlay.md" ] || echo "<!-- Project-specific additions to AGENTS.md for \$name -->" > "\$root/AGENTS-overlay.md"
  [ -f "\$root/AI-WORKFLOW-overlay.md" ] || echo "<!-- Project-specific additions to AI-WORKFLOW.md for \$name -->" > "\$root/AI-WORKFLOW-overlay.md"

  echo ""
  echo "✅ Created project overlay at: \$root"
  echo ""
  echo "Next steps:"
  echo "  1. Edit: \$root/.github/copilot-instructions.md (fill in architecture)"
  echo "  2. Add skill overrides: \$root/.github/skills/<skill-name>/"
  echo "  3. Link: copilot-link-skills \$name"
  echo "Then run 'copilot-link-skills \$name' in your project."
}

# Auto-link on cd (opt-in: export COPILOT_AUTOLINK=1)
# Silently links skills when entering a git repo. No output unless COPILOT_AUTOLINK_VERBOSE=1.
_copilot_autolink_hook() {
  [ "\${COPILOT_AUTOLINK:-0}" = "1" ] || return
  [ -d ".git" ] || return
  # Skip if already linked (check for AGENTS.md symlink or generated file)
  [ -f "AGENTS.md" ] && return
  source "\$COPILOT_SKILLS_ROOT/link-skills.sh"
  if [ "\${COPILOT_AUTOLINK_VERBOSE:-0}" = "1" ]; then
    link_skills
  else
    link_skills >/dev/null 2>&1
  fi
}

# Register hook for zsh (chpwd) and bash (PROMPT_COMMAND)
if [ -n "\${ZSH_VERSION:-}" ]; then
  autoload -U add-zsh-hook 2>/dev/null
  add-zsh-hook chpwd _copilot_autolink_hook 2>/dev/null
elif [ -n "\${BASH_VERSION:-}" ]; then
  _copilot_bash_cd() { builtin cd "\$@" && _copilot_autolink_hook; }
  alias cd='_copilot_bash_cd'
fi

